def _field_score(chapter: Chapter, course: str, title: str, summary: str) -> int:
    score = 0
    for keyword in chapter.keywords:
        if keyword in title:
            score += 4
        elif keyword in course:
            score += 3
        hits = summary.count(keyword)
        if hits:
            score += min(hits, 3)
    return score


def match_syllabus(course: str, title: str, summary: str) -> Chapter | None:
    """按课程名、标题、笔记内容匹配最接近的一章；分数太低就当作匹配不到。"""
    course = course or ""
    title = title or ""
    summary = summary or ""
    best: Chapter | None = None
    best_score = 0
    for chapter in SYLLABUS:
        score = _field_score(chapter, course, title, summary)
        if score > best_score:
            best = chapter
            best_score = score
    # 只在笔记里偶然出现一两个词不算匹配：至少要有标题/课程名的直接命中，
    # 或者正文里反复出现多个关键词。
    if best is None or best_score < 6:
        return None
    return best


def format_syllabus(chapter: Chapter) -> str:
    must = "；".join(chapter.must)
    know = "、".join(chapter.know)
    return (
        f"【408 考纲定位】{chapter.subject} · {chapter.chapter}\n"
        f"必须掌握：{must}\n"
        f"只需了解：{know}\n"
        f"常见考法：{chapter.how}\n"
        "用法：考纲只决定「考哪些、考多深」。题干和答案的事实必须来自笔记，"
        "考纲里有但本节没讲的内容不要出题。"
    )


